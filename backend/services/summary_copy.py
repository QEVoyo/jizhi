# -*- coding: utf-8 -*-
"""学习总结文案库。**里面是两种性质完全不同的东西**，别混用：

┌─────────────────────────────────────────────────────────────────┐
│ FALLBACK_COPY —— 成品文案（**兜底**用）                          │
│   完整的、填好槽就能直接发给用户的中文句子。                       │
│   用在：模型挂了 / 超时 / 返回的不是 JSON。                        │
│   它的意义是「**任何时候都有话说**」—— 没有它，call_llm 一抖      │
│   用户就什么都收不到。                                            │
├─────────────────────────────────────────────────────────────────┤
│ AI_STRUCTURE —— 结构（**给模型**用）                             │
│   不是句子，是「这段该怎么组织」的骨架：先说什么、必须落到什么、    │
│   不许说什么。**一个字都不直接进正文。**                          │
│   用在：提示词里告诉模型「温暖具体长什么样」。                     │
└─────────────────────────────────────────────────────────────────┘

⚠️ 为什么必须是两种，不能共用一套：
   把成品句子塞进提示词，模型会**照着抄**（哪怕写了「换一种说法」也照抄，
   因为整句摆在面前时，改写比生成省力）。结果就是全站用户收到的都是
   同一批句子 —— 而那正是"模板味"的来源。
   给**结构**则相反：模型必须自己组织语言，变化是从生成里来的，不是从
   池子里抽出来的。两者差别在实测里很明显。

其余的规矩（两种都一样）：
  · 槽位只有这几个：{days} {count} {scored} {mastery} {weak} {kp} {behaviors} {actions}
    （⚠️ {count} 是**答题数**，{actions} 是**学习行为数** —— 两个不同的东西，
      写错会出「有 0 次学习动作（查词条 3 次）」这种自相矛盾的句子）
    **FALLBACK_COPY 里不准写死任何数字** —— 数字一律来自真实统计。
    AI_STRUCTURE 里连槽位都不用写，真数字由调用方单独给。
  · 文案里不准出现「昨日」（窗口是 7 天，写昨日就是假话）。
  · 语气**真诚、不油腻**：不能「你真棒！」这种空话，也不能说教。
    好文案是「看到了你做的具体那件事 + 对它的一句判断」，不是打鸡血。
"""

