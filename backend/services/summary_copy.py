def structure_for(bucket: str, section: str) -> str:
    """取一条**结构**给模型（不是句子）。

    同样随机挑 —— 同一个分组连着几天拿到同一种组织方式，写出来也会趋同。
    """
    group = AI_STRUCTURE.get(bucket) or {}
    pool = group.get(section)
    if not pool:
        pool = (AI_STRUCTURE.get("general") or {}).get(section)
    if not pool:
        return ""
    return random.choice(pool)


def bucket_for(*, count: int, scored: int, mastery, kp_topics, learning_count: int) -> str:
    """按「实际发生了什么」选分组。

    ⚠️ 顺序有意义：先看有没有练题，再看批改情况，最后才看别的行为。
       一个练了题的人不该被归到 behaviors_only —— 那样建议会跑偏。
    """
    if count:
        if not scored or mastery is None:
            return "practice_ungraded"
        if mastery >= 80:
            return "practice_good"
        if mastery >= 60:
            return "practice_mid"
        if mastery >= 40:
            return "practice_low"
        return "practice_poor"
    if kp_topics:
        return "plan_only"
    if learning_count:
        return "behaviors_only"
    return "general"


def pick(bucket: str, section: str, **slots) -> str:
    """从分组里随机挑一条并填槽。

    分组/小节缺失时逐级退到 general —— **这个方法永远不返回空串**，
    因为它的全部意义就是在别的地方出问题时兜住底。
    """
    group = FALLBACK_COPY.get(bucket) or {}
    pool = group.get(section)
    if not pool:
        pool = (FALLBACK_COPY.get("general") or {}).get(section)
    if not pool:
        pool = COMMON_ENCOURAGEMENT if section == "encouragement" else []
    if not pool:
        # 连 general 都没有（有人删了文案）—— 硬兜底，宁可平淡也不能空
        return ""

    tpl = random.choice(pool)
    try:
        return tpl.format(**slots)
    except (KeyError, IndexError, ValueError):
        # 模板写错槽位名不该让整条总结挂掉 —— 原样返回，至少还是通顺的中文
        return tpl


def render(bucket: str, **slots) -> dict:
    """一次把三段都生成好（模板模式 / 兜底模式用）。"""
    return {
        "note": pick(bucket, "note", **slots),
        "suggestion": pick(bucket, "suggestion", **slots),
        "encouragement": pick(bucket, "encouragement", **slots)
                        or pick("general", "encouragement", **slots)
                        or "继续。",
    }
